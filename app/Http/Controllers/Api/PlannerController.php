<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Http\Requests\Api\GenerateItineraryRequest;
use App\Http\Resources\ItineraryResource;
use App\Models\Category;
use App\Models\Destination;
use App\Models\Itinerary;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class PlannerController extends Controller
{
    public function generate(GenerateItineraryRequest $request): JsonResponse
    {
        $validated = $request->validated();
        $category = Category::where('slug', $validated['preference'])->first();

        $destinations = Destination::with(['category', 'activities'])
            ->when($category, fn ($query) => $query->where('category_id', $category->id))
            ->orderByDesc('sustainability_score')
            ->orderBy('name')
            ->get();

        if ($destinations->isEmpty()) {
            $destinations = Destination::with(['category', 'activities'])
                ->orderByDesc('sustainability_score')
                ->orderBy('name')
                ->get();
        }

        if ($destinations->isEmpty()) {
            return response()->json([
                'message' => 'No destinations are available to create an itinerary.',
            ], 422);
        }

        $itinerary = DB::transaction(function () use ($request, $validated, $destinations): Itinerary {
            $itinerary = Itinerary::create([
                'user_id' => $request->user()->id,
                'name' => 'EcoJourney ' . ucfirst($validated['preference']) . ' Journey',
                'duration' => $validated['duration'],
                'preference' => $validated['preference'],
                'description' => 'Personalized journey generated by EcoJourney based on travel preference and sustainability score.',
            ]);

            for ($day = 1; $day <= $validated['duration']; $day++) {
                $destination = $destinations[($day - 1) % $destinations->count()];
                $activity = $destination->activities->first();

                $itinerary->items()->create([
                    'destination_id' => $destination->id,
                    'day' => $day,
                    'start_time' => '09:00:00',
                    'description' => $activity?->name ?? 'Explore ' . $destination->name,
                ]);
            }

            return $itinerary;
        });

        $itinerary->load(['items.destination.category', 'items.destination.activities']);

        return response()->json([
            'data' => ItineraryResource::make($itinerary)->resolve(),
        ], 201);
    }

    public function result(Request $request, int $id): JsonResponse
    {
        $itinerary = Itinerary::with([
            'items.destination.category',
            'items.destination.activities',
        ])->where('user_id', $request->user()->id)->findOrFail($id);

        return response()->json([
            'data' => ItineraryResource::make($itinerary)->resolve(),
        ]);
    }
}
